import { cache } from 'react';
import { unstable_cache } from 'next/cache';
import { prisma } from './prisma';

/** Card fields the storefront actually renders. Detail pages load the rest. */
export const productCardSelect = {
  id: true,
  slug: true,
  sku: true,
  nameEn: true,
  nameAr: true,
  purchaseMode: true,
  basePrice: true,
  discountPrice: true,
  currency: true,
  images: true,
  productImages: { select: { path: true, isMain: true, sortOrder: true } },
  isAvailable: true,
  stockQuantity: true,
  warrantyInfoEn: true,
  warrantyInfoAr: true,
  ratingAvg: true,
  ratingCount: true,
  brand: { select: { name: true } },
} as const;

function money(value: { toNumber?: () => number } | number | null | undefined) {
  if (value == null) return null;
  return typeof value === 'number' ? value : Number(value);
}

/** Legacy catalogue imports included very large PNG/JPEG originals. A matching
 * WebP derivative is generated by scripts/optimize-product-images.ts. */
export function optimizeProductImagePath(path: string) {
  return path.startsWith('/products/')
    ? path.replace(/\.(png|jpe?g)$/i, '.webp')
    : path;
}

export function serializeCard<T extends { basePrice?: unknown; discountPrice?: unknown; images?: string[]; productImages?: Array<{ path: string; isMain: boolean; sortOrder: number }> }>(product: T) {
  const importedImages = product.productImages?.slice().sort((a, b) => Number(b.isMain) - Number(a.isMain) || a.sortOrder - b.sortOrder).map((image) => image.path) || [];
  return {
    ...product,
    basePrice: money(product.basePrice as never),
    discountPrice: money(product.discountPrice as never),
    images: (importedImages.length ? importedImages : product.images || []).slice(0, 1).map(img => optimizeProductImagePath(img.startsWith('/uploads/products/evg-product-') ? img.replace('/uploads/products/', '/products/') : img)),
  };
}

export const getSiteSettings = unstable_cache(
  async () => {
    const settings = await prisma.siteSettings.findUnique({ where: { id: 'global' } });
    if (!settings) return {};
    return { ...settings, updatedAt: settings.updatedAt.toISOString() };
  },
  ['site-settings'],
  { revalidate: 300, tags: ['settings'] },
);

export const getHomepageContent = unstable_cache(
  async () => {
    const sections = await prisma.homepageSection.findMany({ where: { isActive: true } });
    return Object.fromEntries(sections.map((section) => [section.key, section]));
  },
  ['homepage-content'],
  { revalidate: 300, tags: ['homepage'] },
);

export const getRootCategories = unstable_cache(
  async () => {
    const categories = await prisma.category.findMany({
      where: { parentId: null },
      orderBy: { nameAr: 'asc' },
      select: {
        id: true,
        slug: true,
        nameAr: true,
        nameEn: true,
        products: {
          where: { isAvailable: true },
          orderBy: { updatedAt: 'desc' },
          take: 1,
          select: { images: true },
        },
        children: {
          orderBy: { nameAr: 'asc' },
          select: {
            products: {
              where: { isAvailable: true },
              orderBy: { updatedAt: 'desc' },
              take: 1,
              select: { images: true },
            },
          },
        },
      },
    });
    return categories.map(({ products, children, ...category }) => {
      const image = products[0]?.images?.[0] || children.flatMap((child) => child.products)[0]?.images?.[0] || null;
      return { ...category, image: image ? optimizeProductImagePath(image) : null };
    });
  },
  ['root-categories'],
  { revalidate: 300, tags: ['categories'] },
);

/** A small, cacheable catalogue slice for the homepage. Keep this selection in
 * sync with ProductCard so the landing page never needs a second product shape. */
export const getHomepageProducts = unstable_cache(
  async () => {
    const available = { isAvailable: true, stockQuantity: { gt: 0 } };
    const [featured, latest] = await Promise.all([
      prisma.product.findMany({
        where: { ...available, isFeatured: true },
        orderBy: [{ updatedAt: 'desc' }],
        take: 4,
        select: productCardSelect,
      }),
      prisma.product.findMany({
        where: available,
        orderBy: [{ createdAt: 'desc' }],
        take: 8,
        select: productCardSelect,
      }),
    ]);

    // A newly populated catalogue may not yet mark any product as featured.
    // In that case, still give visitors a real, useful first product row.
    return {
      featured: (featured.length ? featured : latest.slice(0, 4)).map(serializeCard),
      latest: latest.map(serializeCard),
    };
  },
  ['homepage-products'],
  { revalidate: 120, tags: ['products'] },
);

/** Brand marks are optional editorial content. Only serve local, uploaded
 * assets—never third-party logo URLs—and hide this section when none exist. */
export const getHomepageBrands = unstable_cache(
  async () => {
    const brands = await prisma.brand.findMany({
      where: { logoUrl: { not: null }, products: { some: {} } },
      select: { id: true, name: true, logoUrl: true },
      orderBy: { name: 'asc' },
    });
    return brands.filter((brand): brand is { id: string; name: string; logoUrl: string } => Boolean(brand.logoUrl?.startsWith('/')));
  },
  ['homepage-brands'],
  { revalidate: 300, tags: ['products'] },
);

export const getFilterOptions = unstable_cache(
  async () => {
    const [categories, brands, applications] = await Promise.all([
      prisma.category.findMany({
        select: { id: true, nameEn: true, nameAr: true, slug: true, parentId: true },
        orderBy: { nameEn: 'asc' },
      }),
      prisma.brand.findMany({ select: { id: true, name: true }, orderBy: { name: 'asc' } }),
      prisma.application.findMany({
        select: { id: true, nameEn: true, nameAr: true, slug: true },
        orderBy: { nameEn: 'asc' },
      }),
    ]);
    return {
      categories,
      brands: brands.map((brand) => ({ id: brand.id, nameEn: brand.name, nameAr: brand.name, slug: brand.id })),
      applications,
    };
  },
  ['filter-options'],
  { revalidate: 300, tags: ['categories', 'products'] },
);

/** Dedupes the product read shared by generateMetadata and the page in one request. */
export const getProductBySlug = cache(async (slug: string) => {
  const product = await prisma.product.findUnique({
    where: { slug },
    include: {
      productImages: { orderBy: [{ isMain: 'desc' }, { sortOrder: 'asc' }] },
      brand: { select: { id: true, name: true, logoUrl: true, description: true } },
      categories: { select: { id: true, slug: true, nameEn: true, nameAr: true } },
      applications: { select: { id: true, slug: true, nameEn: true, nameAr: true } },
      specifications: true,
      variants: { orderBy: { titleEn: 'asc' } },
      accessories: { select: productCardSelect },
    },
  });

  if (product) {
    if (product.productImages.length) product.images = [...product.productImages].sort((a, b) => Number(b.isMain) - Number(a.isMain) || a.sortOrder - b.sortOrder).map((image) => image.path);
    product.images = product.images.map(img => optimizeProductImagePath(img.startsWith('/uploads/products/evg-product-') ? img.replace('/uploads/products/', '/products/') : img));
    // Import provenance/model data is internal. Do not serialize it into the
    // public product page payload or any server-rendered storefront response.
    const { seriesModel: _internalSeriesModel, ...publicProduct } = product;
    return publicProduct;
  }

  return null;
});
