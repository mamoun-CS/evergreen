function money(value: { toNumber?: () => number } | number | null | undefined) {
  if (value == null) return null;
  return typeof value === 'number' ? value : Number(value);
}

/** Legacy catalogue imports included very large PNG/JPEG originals. A matching
 * WebP derivative is generated by scripts/optimize-product-images.ts. Missing
 * derivatives must keep the original path: a rewritten URL falls through to
 * the /products/[slug] page and Next.js Image then receives HTML. */
let productWebpNames: Set<string> | null = null;
function productWebpExists(filename: string) {
  if (!productWebpNames) {
    const directory = path.join(process.cwd(), 'public', 'products');
    productWebpNames = new Set(
      fs.existsSync(directory)
        ? fs.readdirSync(directory).filter((name) => name.toLowerCase().endsWith('.webp'))
        : [],
    );
  }
  return productWebpNames.has(filename);
}

export function optimizeProductImagePath(imagePath: string) {
  if (!imagePath.startsWith('/products/')) return imagePath;
  const webpPath = imagePath.replace(/\.(png|jpe?g)$/i, '.webp');
  if (webpPath === imagePath) return imagePath;
  const filename = webpPath.slice('/products/'.length);
  return productWebpExists(filename) ? webpPath : imagePath;
}

export function serializeCard<T extends { basePrice?: unknown; discountPrice?: unknown; images?: string[]; productImages?: Array<{ path: string; isMain: boolean; sortOrder: number }> }>(product: T) {
  const importedImages = product.productImages?.slice().sort((a, b) => Number(b.isMain) - Number(a.isMain) || a.sortOrder - b.sortOrder).map((image) => image.path) || [];
  const { productImages: _imageRecords, ...card } = product;
  return {
    ...card,
    basePrice: money(product.basePrice as never),
    discountPrice: money(product.discountPrice as never),
    images: (importedImages.length ? importedImages : product.images || []).slice(0, 1).map(img => optimizeProductImagePath(img.startsWith('/uploads/products/evg-product-') ? img.replace('/uploads/products/', '/products/') : img)),
  };
}

